export function writingTopicSuggestions(
  grade: number,
  paper: 1 | 2,
  taskId: string,
  choice?: string,
): readonly string[] {
  if (grade !== 6) return [];
  if (paper === 1 && ["story", "paragraph", "dialogue"].includes(taskId))
    return classSixWritingTopics[taskId];
  if (paper === 2 && taskId === "composition")
    return classSixWritingTopics.composition;
  if (
    paper === 2 &&
    taskId === "letter-email" &&
    choice &&
    [
      "formal-letter",
      "informal-letter",
      "formal-email",
      "informal-email",
    ].includes(choice)
  )
    return classSixWritingTopics[choice];
  return [];
}
export function searchWritingTopics(topics: readonly string[], query: string) {
  const words = query
    .normalize("NFKC")
    .toLocaleLowerCase()
    .trim()
    .split(/\s+/)
    .filter(Boolean);
  return topics.filter((topic) =>
    words.every((word) =>
      topic.normalize("NFKC").toLocaleLowerCase().includes(word),
    ),
  );
}
